#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
GEN="$ROOT/internal/plugin/builtin/imports_gen.go"
{
  printf '// Code generated by scripts/dev/gen-builtin-plugins.sh; DO NOT EDIT.\npackage builtin\nimport (\n'
  for plugin_dir in "$ROOT"/plugins/*; do
    [[ -f "$plugin_dir/register.go" ]] || continue
    printf '\t_ "github.com/ybz21/Roami/plugins/%s"\n' "$(basename "$plugin_dir")"
  done
  printf ')\n'
} > "$GEN"
gofmt -w "$GEN"
